_UNIT_USD = '<xbrli:unit id="usd"><xbrli:measure>iso4217:USD</xbrli:measure></xbrli:unit>'
_UNIT_SHARES = '<xbrli:unit id="shares"><xbrli:measure>xbrli:shares</xbrli:measure></xbrli:unit>'


def _build(resources: str, body: str) -> str:
    return _XHTML_HEADER.format(resources=resources, body=body)


def _write_and_parse(tmp_path, xml_text: str):
    path = tmp_path / "fixture.htm"
    path.write_text(xml_text, encoding="utf-8")
    return parse_xml(path)


