@pytest.mark.local_data
def test_numeric_normalization_matches_real_xbrl_fact():
    """Independent validation against a real data/xbrl.duckdb row - see
    module docstring. Never used to derive the normalization rule
    itself, only to confirm it after being written from the XBRL spec."""
    import duckdb
    from src.storage import get_storage
    from src.parse import inline_xbrl as ix

    storage = get_storage()
    path = storage.primary_docs_root / "100122" / "0000100122-24-000002.htm"
    if not path.exists():
        pytest.skip("real primary filing not present")

    root = ix.parse_xml(path)
    contexts = ix.extract_contexts(root)
    facts = ix.extract_inline_facts(root)
    revenues = [f for f in facts if f.concept_qname == "us-gaap:Revenues" and f.context_ref == "c-1"]
    assert revenues, "expected fact not found - real filing structure may have changed"
    fact = revenues[0]
    period = ix.context_to_truth_contract_period(contexts["c-1"])

    con = duckdb.connect(str(storage.repo_root / "data" / "xbrl.duckdb"), read_only=True)
    try:
        row = con.execute(
            "SELECT value FROM facts WHERE adsh=? AND tag='Revenues' AND ddate=? AND qtrs=? AND uom='USD' "
            "AND (coreg IS NULL OR coreg='') AND (segments IS NULL OR segments='')",
            ["0000100122-24-000002", period.ddate, period.qtrs],
        ).fetchone()
    finally:
        con.close()
    assert row is not None
    assert float(fact.normalized_value) == float(row[0])
